"""Export the shared definitions (themes, names, events, methods) from the Python package to the mobile app
so both versions stay identical.  Usage: python tools/export_web.py"""
import json, os, shutil, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
sys.path.insert(0, ROOT)
from mawaqit import themes, events, calc, paths

WWW = os.path.join(ROOT, 'android-app', 'www')
os.makedirs(os.path.join(WWW, 'engine'), exist_ok=True)


def keyed(d):  # tuple keys -> "m-d"
    return {'%d-%d' % k: v for k, v in d.items()}


shared = dict(
    version=paths.VERSION,
    themes={k: dict(ar=v['name_ar'], en=v['name_en'], css=themes.css_for(k)) for k, v in themes.THEMES.items()},
    themeOrder=themes.ORDER,
    HIJRI=events.HIJRI, GREG=events.GREG, DAYS=events.DAYS, UI=events.UI,
    HIJRI_EVENTS=keyed(events.HIJRI_EVENTS), HIJRI_EVENTS_MA=keyed(events.HIJRI_EVENTS_MA),
    NATIONAL={cc: keyed(v) for cc, v in events.NATIONAL.items()},
    METHODS=calc.METHODS, METHOD_ORDER=calc.METHOD_ORDER, COUNTRY_METHOD=calc.COUNTRY_METHOD,
    HANAFI=sorted(calc.HANAFI_COUNTRIES), MOROCCO_CALIB=calc.MOROCCO_CALIB,
)
with open(os.path.join(WWW, 'engine', 'shared.js'), 'w', encoding='utf-8') as fh:
    fh.write('// generated by tools/export_web.py – do not edit\nexport const S = ')
    json.dump(shared, fh, ensure_ascii=False)
    fh.write(';\n')
for sub in ('fonts', 'data'):
    dst = os.path.join(WWW, sub)
    shutil.rmtree(dst, ignore_errors=True)
    shutil.copytree(os.path.join(ROOT, 'mawaqit', sub), dst)
# Android's asset packager strips/decompresses *.gz files: ship it under a neutral extension
os.replace(os.path.join(WWW, 'data', 'places.json.gz'), os.path.join(WWW, 'data', 'places.dat'))
print('exported to', WWW)
